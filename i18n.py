"""
i18n.py
ระบบสองภาษา (ไทย/อังกฤษ)
ทุกข้อความในโปรแกรมเขียนคู่กันไว้ตรงที่ใช้เลย เช่น tr("ล้างไฟล์ขยะ", "Clean junk")
ข้อดีคือเวลาแก้ข้อความจะเห็นทั้งสองภาษาพร้อมกัน ไม่ต้องไปตามหาในไฟล์แปลแยก
ข้อความที่ประกาศไว้ล่วงหน้า (เช่นรายชื่อหมวดไฟล์ขยะ) เก็บเป็น tuple (ไทย, อังกฤษ) แล้วเรียก tx() ตอนแสดงผล
"""

_lang = "th"


def set_language(lang):
    """ตั้งภาษาที่ใช้ทั้งโปรแกรม ('th' หรือ 'en')"""
    global _lang
    _lang = "en" if lang == "en" else "th"


def get_language():
    """คืนภาษาที่ใช้อยู่ตอนนี้"""
    return _lang


def tr(th, en=None):
    """เลือกข้อความตามภาษาปัจจุบัน ถ้าไม่มีคำแปลอังกฤษจะใช้ภาษาไทย"""
    return en if _lang == "en" and en is not None else th


def tx(value):
    """แปลงค่าที่เป็น tuple (ไทย, อังกฤษ) ให้เป็นข้อความตามภาษาปัจจุบัน ถ้าเป็นข้อความธรรมดาคืนตามเดิม"""
    if isinstance(value, tuple) and len(value) == 2:
        return tr(*value)
    return value
